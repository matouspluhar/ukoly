import assert from 'node:assert/strict';
import { parseZakazky, groupOf, groupTasks, dueLabel } from '../js/format.js';
const names = parseZakazky('# Zakázky\n- 2620 Paseka\n- 2612 ZŠ Lázně Bohdaneč\n| 2601 | Divadlo Plzeň |\n');
assert.deepEqual(names, { '2620': 'Paseka', '2612': 'ZŠ Lázně Bohdaneč', '2601': 'Divadlo Plzeň' });
const mk = (fm) => ({ fm: { stav: 'otevreno', ohen: false, termin: '', ...fm } });
let g = groupOf(mk({ nazev: 'Paseka – zpracovat skutečné provedení stavby', zakazka: '2620' }), names);
assert.equal(g.key, 'z:2620'); assert.equal(g.label, 'Paseka'); assert.equal(g.title, 'zpracovat skutečné provedení stavby');
g = groupOf(mk({ nazev: 'Peníze – zálohy doplatit' }), names);
assert.equal(g.key, 'p:penize'); assert.equal(g.label, 'Peníze'); assert.equal(g.title, 'zálohy doplatit');
g = groupOf(mk({ nazev: 'Do konce roku závazně rozhodnout, co dál s HSN, transferem a TUL' }), names);
assert.equal(g.key, 'ostatni');
g = groupOf(mk({ nazev: 'Poslat klientovi revizi', zakazka: '2612' }), names);
assert.equal(g.label, 'ZŠ Lázně Bohdaneč'); assert.equal(g.title, 'Poslat klientovi revizi');
const gs = groupTasks([mk({ nazev: 'x' }), mk({ nazev: 'Peníze – a' }), mk({ nazev: 'Paseka – b', zakazka: '2620', ohen: true })], names);
assert.deepEqual(gs.map((x) => x.key), ['z:2620', 'p:penize', 'ostatni']);
assert.equal(dueLabel('2026-11-24', '2026-11-24').text, 'dnes');
assert.equal(dueLabel('2026-11-25', '2026-11-24').text, 'zítra');
assert.equal(dueLabel('2026-11-28', '2026-11-24').text, 'so 28. 11.');
assert.ok(dueLabel('2026-11-20', '2026-11-24').overdue);
console.log('group: testy prošly');
assert.deepEqual(parseZakazky('- HSN Hlavně se neposrat\n# Nadpis\n'), { HSN: 'Hlavně se neposrat' }); console.log('kódy oblastí OK');
